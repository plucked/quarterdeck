#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use super::*;

    /// No key appears twice in a table, where the later entry would never match.
    #[test]
    fn keys_are_unique() {
        for table in [FILE_NAME_ICONS, FILE_NAME_PREFIX_ICONS, EXTENSION_ICONS] {
            let mut seen = HashSet::new();
            for (key, _) in table {
                assert!(seen.insert(*key), "{key} is listed twice");
                assert_eq!(*key, key.to_lowercase(), "{key} is not lower case");
            }
        }
    }
}
