/// The palette of `theme`.
pub fn palette_of(theme: ColorTheme) -> &'static Palette {
    match theme {
        ColorTheme::Ledger => &LEDGER,
        ColorTheme::Vellum => &VELLUM,
        ColorTheme::Overcast => &OVERCAST,
        ColorTheme::Signal => &SIGNAL,
        ColorTheme::Graphite => &GRAPHITE,
        ColorTheme::Tide => &TIDE,
        ColorTheme::Lantern => &LANTERN,
        ColorTheme::Beacon => &BEACON,
    }
}
